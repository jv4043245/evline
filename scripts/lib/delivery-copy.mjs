// Owner-approved public delivery promise, 2026-09-23. This changes marketing
// copy only, not order-specific dates, CRM records, prices or sea shipping.
export function currentDeliveryCopy(source) {
  return source
    .replaceAll('<b>14,5 днів</b><span>середній строк авіа</span>', '<b>Від 20 днів</b><span>доставка авіа</span>')
    .replaceAll('<b>14,5 дней</b><span>средний срок авиа</span>', '<b>От 20 дней</b><span>доставка авиа</span>')
    .replaceAll('через 18–20 днів авіа', 'від 20 днів авіа')
    .replaceAll('через 18–20 дней авиа', 'от 20 дней авиа')
    .replaceAll('орієнтовно 18–20 днів', 'від 20 днів; точний строк підтвердить менеджер')
    .replaceAll('ориентировочно 18–20 дней', 'от 20 дней; точный срок подтвердит менеджер')
    .replaceAll('обычно занимает около 18–20 дней', 'занимает от 20 дней; точный срок подтвердит менеджер')
    .replace(/([Вв]ід) 14 днів/g, '$1 20 днів')
    .replace(/([Оо]т) 14 дней/g, '$1 20 дней')
    .replace(/([Аа]віа(?: —)?(?: орієнтовно)?) 14 днів/g, '$1 від 20 днів')
    .replace(/([Аа]виа(?: —)?(?: ориентировочно)?) 14 дней/g, '$1 от 20 дней')
    .replace(/([Аа]віа) 14 \/ море/g, '$1 від 20 / море')
    .replace(/([Аа]виа) 14 \/ море/g, '$1 от 20 / море')
    .replace(/([Аа]виа от) 14 \/ море/g, '$1 20 / море')
    .replaceAll('від 14 і море від 60 днів', 'від 20 і море від 60 днів')
    .replaceAll('от 14 и море от 60 дней', 'от 20 и море от 60 дней')
    .replaceAll('у строках 14 проти 60 днів', 'у строках від 20 проти 60 днів')
    .replaceAll('в сроках 14 против 60 дней', 'в сроках от 20 против 60 дней');
}
